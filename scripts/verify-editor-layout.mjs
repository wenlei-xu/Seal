import fs from 'node:fs/promises';
import path from 'node:path';
import http from 'node:http';
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { createProjectStore } from '../edit-host/project-store.mjs';
import { initializeProject } from '../edit-host/starter.mjs';
import { createStudioGateway } from '../edit-host/studio-gateway.mjs';
const require = createRequire(new URL('../edit-host/package.json', import.meta.url));
const puppeteer = require('puppeteer-core');

const directory = path.resolve('.local/cache/editor-layout-smoke', `run-${Date.now()}`);
const store = createProjectStore(directory);
const edit = await store.ensure('layout_smoke');
await initializeProject(store.workDir(edit.editId));
const gateway = createStudioGateway(store);
const owned = await gateway.open(edit.editId);
let browser;
const errors = [];
const parent = http.createServer((req,res) => {
  res.setHeader('Content-Type','text/html');
  const launch = owned.ticket(`http://127.0.0.1:${parent.address().port}`);
  res.end(`<html><body style="margin:0;background:#171717"><form method="post" action="${launch.studioUrl}/__session" target="studio"><input name="ticket" value="${launch.ticket}"></form><iframe name="studio" style="width:100vw;height:100vh;border:0"></iframe><script>document.querySelector('form').submit();document.querySelector('form').hidden=true;</script></body></html>`);
});
await new Promise(resolve => parent.listen(0,'127.0.0.1',resolve));
try {
  assert.ok(process.env.HYPERFRAMES_BROWSER_PATH, 'Set HYPERFRAMES_BROWSER_PATH to the local browser executable');
  browser = await puppeteer.launch({ executablePath: process.env.HYPERFRAMES_BROWSER_PATH, headless:true });
  const page = await browser.newPage();
  page.on('pageerror',error => errors.push(error.message));
  await page.setViewport({width:1440,height:860});
  await page.goto(`http://127.0.0.1:${parent.address().port}`);
  await page.waitForFunction(() => [...document.querySelectorAll('iframe')].some(frame => frame.contentWindow));
  let frame;
  for(let attempt=0;attempt<60;attempt++) {
    frame=page.frames().find(frame => frame.url().startsWith(owned.origin));
    if (frame && await frame.$('.bf-library')) break;
    await new Promise(resolve=>setTimeout(resolve,500));
  }
  if(!frame || !await frame.$('.bf-library')) throw new Error(`Editor failed to mount: ${errors.join('; ')}`);
  await frame.waitForSelector('.bf-timeline-tools');
  await frame.click('.bf-library-tabs button:nth-child(3)');
  await frame.click('.bf-text-tools textarea');
  await frame.$eval('.bf-text-tools textarea', input => { const setter=Object.getOwnPropertyDescriptor(HTMLTextAreaElement.prototype,'value').set;setter.call(input,'布局验收标题');input.dispatchEvent(new Event('input',{bubbles:true})); });
  await frame.click('.bf-text-tools .bf-primary');
  await frame.waitForSelector('.bf-track-header',{timeout:30000});
  await frame.waitForFunction(() => window.__BeeftvEditor.actions && document.querySelector('[data-clip]'));
  const clip = await frame.$('[data-clip]');
  await clip.click();
  await frame.waitForSelector('.bf-inspector-tabs');
  await frame.evaluate(() => document.fonts.ready);
  const typography = await frame.$eval('.bf-tool', button => ({family:getComputedStyle(button).fontFamily,style:getComputedStyle(button).fontStyle,loaded:document.fonts.check('12px "BeefTV UI Sans"')}));
  assert.match(typography.family,/BeefTV UI Sans/); assert.equal(typography.style,'normal'); assert.equal(typography.loaded,true);
  await frame.click('.bf-track-header button[data-control="visibility"]');
  await frame.waitForSelector('.bf-track-header [data-icon="eye-off"]');
  await frame.waitForFunction(() => !document.querySelector('.bf-track-header button[data-control="visibility"]').disabled);
  assert.equal(await frame.$eval('.bf-track-header button[data-control="visibility"]',button=>button.getAttribute('aria-pressed')),'true');
  await frame.click('.bf-track-header button[data-control="visibility"]');
  await frame.waitForSelector('.bf-track-header [data-icon="eye"]');
  await frame.waitForFunction(() => !document.querySelector('.bf-track-header button[data-control="visibility"]').disabled);
  const trim = await frame.$('button[aria-label="删除播放头左侧"]');
  await trim.hover();
  await frame.waitForFunction(() => [...document.querySelectorAll('[role="tooltip"]')].some(element => element.textContent.includes('保留右侧')));
  await page.screenshot({path:path.join(directory,'editor-polished.png')});
  await frame.click('button[aria-label="更多时间线工具"]');
  await frame.waitForSelector('.bf-more-panel');
  await page.keyboard.press('Escape');
  await frame.waitForFunction(() => !document.querySelector('.bf-more-panel') && document.activeElement?.getAttribute('aria-label') === '更多时间线工具');
  await page.keyboard.press('Home');
  assert.equal(await frame.evaluate(() => document.activeElement.getAttribute('aria-label')),'导入素材');
  await frame.click('button[aria-label="更多时间线工具"]');
  await frame.waitForSelector('.bf-more-panel');
  await frame.$eval('input[aria-label="轨道高度"]', input => { const setter=Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set;setter.call(input,'96');input.dispatchEvent(new Event('input',{bubbles:true})); });
  await frame.click('button[aria-label="大波形"]');
  const height = await frame.$eval('.bf-track-header', element => element.getBoundingClientRect().height);
  assert.equal(height,96);
  await frame.click('.bf-inline');
  await frame.click('button[aria-label="锁定轨道"]');
  const isLocked = await frame.evaluate(() => document.querySelector('button[aria-label="在播放头处分割选中片段"]').disabled);
  assert.equal(isLocked,true);
  await frame.click('button[aria-label="解锁轨道"]');
  await frame.evaluate(() => window.__BeeftvEditor.actions && window.__BeeftvEditor.player.getState().requestSeek(1.5));
  await frame.click('button[aria-label="在播放头处分割选中片段"]');
  await frame.waitForFunction(() => window.__BeeftvEditor.player.getState().elements.length === 2);
  await frame.waitForFunction(() => !document.querySelector('button[aria-label="撤销（Ctrl+Z）"]').disabled);
  await frame.click('button[aria-label="撤销（Ctrl+Z）"]');
  await frame.waitForFunction(() => window.__BeeftvEditor.player.getState().elements.length === 1);
  const source = await fs.readFile(path.join(store.workDir(edit.editId),'index.html'),'utf8');
  assert.match(source,/布局验收标题/);
  const editorText = await frame.$eval('body', element=>element.textContent);
  assert(!editorText.includes('index.html'));
  assert(!editorText.includes('展开关键帧'));
  await page.screenshot({path:path.join(directory,'editor.png')});
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({pass:true,screenshot:path.join(directory,'editor.png'),polishedScreenshot:path.join(directory,'editor-polished.png'),revision:(await store.state(edit.editId)).revision,checks:['mount','add-text','select-inspector','upright-font','visibility-icons','trim-tooltip','keyboard-focus','track-height','wave-share','lock','split','undo','hide-code']},null,2));
} finally {
  await browser?.close();
  parent.closeAllConnections();
  await new Promise(resolve=>parent.close(resolve));
  await gateway.close();
}
